#!/usr/bin/env bash
# Regenerates src/lifecycle-icons.mjs: the small icons beside the facts of the
# lifecycle cards (start and last will) as embedded PNG data URIs.
#
# - Service logos (Node.js, Home Assistant) come from Simple Icons (CC0 1.0),
#   flattened to the brand colour. GitLab and Jira reuse the logos of
#   card-icons.mjs, they are not generated here.
# - Utility glyphs (host, memory, clock, ...) come from Lucide (ISC), drawn in
#   one neutral gray that stays readable on a light and a dark Teams theme.
#
# Needs npm, tar, jq and ImageMagick (with the librsvg delegate).
#
# Usage: scripts/gen-lifecycle-icons.sh [SIMPLE_ICONS_VERSION] [LUCIDE_VERSION]

set -euo pipefail

si_version="${1:-latest}"
lucide_version="${2:-latest}"
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

fetch() {
  local pkg="$1" version="$2" license="$3" dir="$4"
  mkdir -p "$work/$dir"
  (cd "$work/$dir" && npm pack --silent "${pkg}@${version}" >/dev/null 2>&1 && tar -xzf ./*.tgz)
  [[ "$(jq -r .license "$work/$dir/package/package.json")" == "$license" ]] || {
    echo "unexpected license for $pkg" >&2
    exit 1
  }
  jq -r .version "$work/$dir/package/package.json"
}

si_resolved="$(fetch simple-icons "$si_version" CC0-1.0 si)"
lucide_resolved="$(fetch lucide-static "$lucide_version" ISC lucide)"
si_src="$work/si/package/icons"
lucide_src="$work/lucide/package/icons"

neutral="#8a8a92"

# key:source:glyph:colour:alt text
icons=(
  "node:si:nodedotjs:#5fa04e:Node.js"
  "homeassistant:si:homeassistant:#18bcf2:Home Assistant"
  "host:lucide:server:${neutral}:Host"
  "pid:lucide:hash:${neutral}:PID"
  "memory:lucide:memory-stick:${neutral}:Memory"
  "started:lucide:calendar-clock:${neutral}:Started"
  "conversations:lucide:messages-square:${neutral}:Watched conversations"
  "cache:lucide:database:${neutral}:Cache"
  "signal:lucide:zap:${neutral}:Signal"
  "uptime:lucide:timer:${neutral}:Uptime"
  "time:lucide:clock:${neutral}:Time"
)

# Drawn at 3x and shown at 16px; a small palette keeps each icon a few hundred
# bytes (a card is limited in size).
px=16
s=3
out="$root/src/lifecycle-icons.mjs"
{
  cat <<HEADER
// Icons beside the facts of the lifecycle cards, as ${px}px images (3x PNG data
// URIs, generated by scripts/gen-lifecycle-icons.sh, do not edit by hand).
// \`alt\` is the icon in words for screen readers.
//
// Logos (Node.js, Home Assistant) are from Simple Icons ${si_resolved} (CC0 1.0),
// flattened to the brand colour; the logos are trademarks of their owners and
// only identify the service. Utility glyphs are from Lucide ${lucide_resolved} (ISC), in one
// neutral gray. GitLab and Jira reuse the logos of card-icons.mjs.

export const LIFECYCLE_ICONS_PX = ${px};

export const LIFECYCLE_ICONS = {
HEADER
  for spec in "${icons[@]}"; do
    IFS=: read -r key source glyph colour alt <<<"$spec"
    if [[ "$source" == si ]]; then
      sed "s/<path /<path fill=\"${colour}\" /g" "$si_src/${glyph}.svg" >"$work/${key}.svg"
    else
      sed "s/currentColor/${colour}/g" "$lucide_src/${glyph}.svg" >"$work/${key}.svg"
    fi
    magick -background none -density 1536 "$work/${key}.svg" -resize "$((px * s))x$((px * s))" \
      +dither -colors 16 -strip -define png:format=png8 -define png:compression-level=9 "$work/${key}.png"
    printf "  '%s': {\n    alt: '%s',\n    url:\n      'data:image/png;base64,%s',\n  },\n" "$key" "$alt" "$(base64 -w0 "$work/${key}.png")"
  done
  echo "};"
} >"$out"
echo "wrote $out"
