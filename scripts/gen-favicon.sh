#!/usr/bin/env bash
# Regenerates the pictures of the web pages from cover.png (the /approve cap), as PNG data URIs (the pages' CSP
# allows data: images only): src/favicon.mjs (64x64, transparent) and src/pwa-icons.mjs (192 and 512, the cap
# on a light square with room around it, also usable as maskable icons). Needs ImageMagick.
set -euo pipefail
cd "$(dirname "$0")/.."
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
magick cover.png -trim +repage -resize 64x64 -background none -gravity center -extent 64x64 -strip \
  -define png:compression-level=9 "$tmp/favicon.png"
{
  echo '// Generated by scripts/gen-favicon.sh from cover.png: the /approve cap, 64x64 PNG. Do not edit.'
  printf "export const FAVICON = 'data:image/png;base64,%s';\n" "$(base64 -w0 "$tmp/favicon.png")"
} >src/favicon.mjs
for size in 192 512; do
  inner=$((size * 62 / 100))
  magick cover.png -trim +repage -resize "${inner}x${inner}" -background '#ececef' -gravity center \
    -extent "${size}x${size}" -strip -colors 128 -define png:compression-level=9 "$tmp/icon-$size.png"
done
{
  echo '// Generated by scripts/gen-favicon.sh from cover.png: the app icons of the dashboard (PNG, base64). Do not edit.'
  printf "export const ICON_192 = '%s';\n" "$(base64 -w0 "$tmp/icon-192.png")"
  printf "export const ICON_512 = '%s';\n" "$(base64 -w0 "$tmp/icon-512.png")"
} >src/pwa-icons.mjs
