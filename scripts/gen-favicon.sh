#!/usr/bin/env bash
# Regenerates src/favicon.mjs: the /approve cap of cover.png as a 64x64 PNG data URI (the web pages' CSP allows
# data: images only). Needs ImageMagick.
set -euo pipefail
cd "$(dirname "$0")/.."
tmp="$(mktemp --suffix=.png)"
trap 'rm -f "$tmp"' EXIT
magick cover.png -trim +repage -resize 64x64 -background none -gravity center -extent 64x64 -strip \
  -define png:compression-level=9 "$tmp"
{
  echo '// Generated by scripts/gen-favicon.sh from cover.png: the /approve cap, 64x64 PNG. Do not edit.'
  printf "export const FAVICON = 'data:image/png;base64,%s';\n" "$(base64 -w0 "$tmp")"
} >src/favicon.mjs
