#!/usr/bin/env bash
# Regenerates src/approval-badge-images.mjs: GitLab-style approval badges for the
# merge request card: a teal "Approved" pill with the approval glyph, and a muted
# gray pill with the dashed-circle glyph for a merge request that still waits
# for approvals ("Not approved yet", or "N of M Approvals" for the counts GitLab
# reports). Like the state badges (scripts/gen-mr-badges.sh) they are static
# PNG data URIs: a card cannot paint a pill in GitLab's own colours. Needs npm,
# tar, jq and ImageMagick (with the librsvg delegate).
#
# Usage: scripts/gen-approval-badges.sh [VERSION]   (default: 3.174.0, the
# version of the other GitLab assets; set FONT to a bold sans-serif .ttf;
# MAX_REQUIRED, default 6, is the highest "of M" that gets an image)

set -euo pipefail

version="${1:-3.174.0}"
max_required="${MAX_REQUIRED:-6}"
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
font="${FONT:-$(fc-match -f '%{file}' 'sans-serif:bold')}"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

(cd "$work" && npm pack --silent "@gitlab/svgs@${version}" >/dev/null 2>&1 && mkdir pkg && tar -xzf ./*.tgz -C pkg)
src="$work/pkg/package/dist/sprite_icons"
[[ "$(jq -r .license "$work/pkg/package/package.json")" == "MIT" ]] || {
  echo "unexpected license" >&2
  exit 1
}

# Same geometry as the state badges: drawn at 3x, shown at 22px high with a
# 14px glyph and 12px bold text; a 48-colour palette keeps a badge near 2 KB.
s=3
h=$((22 * s))
glyph=$((14 * s))
font_px=$((12 * s))
pad=$((8 * s))
gap=$((4 * s))

# key|label|icon|glyph colour|background|border|text colour
# approved: the dark teal on light teal of the open state badge; pending: the
# neutral gray of the draft badge. Both keep WCAG AA contrast (4.5:1).
specs=("approved|Approved|approval|#0b5a4b|#c5ece3|#7fcab8|#0b5a4b")
pending=("pending|Not approved yet")
for ((m = 1; m <= max_required; m++)); do
  for ((n = 0; n < m; n++)); do
    pending+=("pending-${n}-of-${m}|${n} of ${m} Approvals")
  done
done
for p in "${pending[@]}"; do
  specs+=("${p}|dotted-circle|#4a4950|#ececef|#bfbfc3|#4a4950")
done

out="$root/src/approval-badge-images.mjs"
{
  cat <<HEADER
// GitLab-style approval badges: a pill with a glyph and the approval state in
// words, as 3x PNG data URIs shown at \`width\` x \`height\` pixels (generated by
// scripts/gen-approval-badges.sh, do not edit by hand; use src/approval-badges.mjs).
//
// The glyphs come from @gitlab/svgs ${version} (MIT, Copyright (c) 2011-present
// GitLab Inc.); the text is rendered into the image, so \`alt\` carries it for
// screen readers. Keys: \`approved\`, \`pending\` ("Not approved yet") and
// \`pending-N-of-M\` for M up to ${max_required}.

export const APPROVAL_BADGE_IMAGES = {
HEADER
  for spec in "${specs[@]}"; do
    IFS='|' read -r key label icon glyph_colour bg border text_colour <<<"$spec"
    sed "s/<path /<path fill=\"${glyph_colour}\" /g" "$src/${icon}.svg" >"$work/${key}.svg"
    magick -background none -density 1536 "$work/${key}.svg" -resize "${glyph}x${glyph}" \
      "PNG32:$work/${key}-glyph.png"
    magick -background none -fill "$text_colour" -font "$font" -pointsize "$font_px" \
      "label:${label}" -trim +repage "PNG32:$work/${key}-text.png"
    text_w="$(magick identify -format '%w' "$work/${key}-text.png")"
    text_h="$(magick identify -format '%h' "$work/${key}-text.png")"
    w=$((pad + glyph + gap + text_w + pad))
    w=$(((w + s - 1) / s * s))
    r=$((h / 2))
    magick -size "${w}x${h}" xc:none -fill "$bg" -stroke "$border" -strokewidth "$s" \
      -draw "roundrectangle $((s / 2)),$((s / 2)) $((w - 1 - s / 2)),$((h - 1 - s / 2)) $r,$r" \
      "$work/${key}-glyph.png" -geometry "+${pad}+$(((h - glyph) / 2))" -composite \
      "$work/${key}-text.png" -geometry "+$((pad + glyph + gap))+$(((h - text_h) / 2))" -composite \
      +dither -colors 48 -strip -define png:format=png8 -define png:compression-level=9 \
      "$work/${key}.png"
    printf "  '%s': {\n    alt: '%s',\n    width: %d,\n    height: %d,\n    url:\n      'data:image/png;base64,%s',\n  },\n" \
      "$key" "$label" "$((w / s))" "$((h / s))" "$(base64 -w0 "$work/${key}.png")"
  done
  echo "};"
} >"$out"
echo "wrote $out"
