#!/usr/bin/env bash
# Regenerates src/gitlab-icons.mjs from the upstream @gitlab/svgs package
# (MIT). Needs npm, tar and ImageMagick (with the librsvg delegate).
#
# Usage: scripts/gen-gitlab-icons.sh [VERSION]   (default: latest)

set -euo pipefail

version="${1:-latest}"
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

(cd "$work" && npm pack --silent "@gitlab/svgs@${version}" >/dev/null 2>&1 && mkdir pkg && tar -xzf ./*.tgz -C pkg)
src="$work/pkg/package/dist/sprite_icons"
pkg_version="$(jq -r .version "$work/pkg/package/package.json")"
[[ "$(jq -r .license "$work/pkg/package/package.json")" == "MIT" ]] || {
  echo "unexpected license" >&2
  exit 1
}

# name:colour (GitLab's own status colours)
icons=(
  merge-request-open:#2da160
  merge:#1f75cb
  merge-request-close:#dd2b0e
  pipeline:#1f75cb
  status_success:#2da160
  status_failed:#dd2b0e
  status_running:#1f75cb
  status_pending:#c17d10
  status_canceled:#737278
  status_skipped:#737278
  status_manual:#1f75cb
  status_created:#737278
)

out="$root/src/gitlab-icons.mjs"
{
  cat <<HEADER
// GitLab iconography for the card headers: 48x48 PNG data URIs (generated by
// scripts/gen-gitlab-icons.sh, do not edit by hand).
//
// The glyphs come from @gitlab/svgs ${pkg_version} (MIT, Copyright (c) 2011-present
// GitLab Inc.), flattened to one GitLab status colour each so they stay legible
// on light and dark themes.

export const GITLAB_ICONS = {
HEADER
  for spec in "${icons[@]}"; do
    name="${spec%%:*}"
    colour="${spec##*:}"
    sed "s/<path /<path fill=\"${colour}\" /g" "$src/${name}.svg" >"$work/${name}.svg"
    magick -background none -density 768 "$work/${name}.svg" -resize 48x48 \
      -depth 8 -strip -define png:compression-level=9 "PNG32:$work/${name}.png"
    printf "  '%s':\n    'data:image/png;base64,%s',\n" "$name" "$(base64 -w0 "$work/${name}.png")"
  done
  echo '};'
} >"$out"
echo "wrote $out"
