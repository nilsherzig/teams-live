#!/usr/bin/env bash
# Regenerates src/gitlab-icons.mjs (header icons) and src/gitlab-icons-small.mjs
# (compact list icons) from the upstream @gitlab/svgs package (MIT). Needs npm,
# tar and ImageMagick (with the librsvg delegate).
#
# Usage: scripts/gen-gitlab-icons.sh [VERSION]   (default: latest)

set -euo pipefail

version="${1:-latest}"
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

(cd "$work" && npm pack --silent "@gitlab/svgs@${version}" >/dev/null 2>&1 && mkdir pkg && tar -xzf ./*.tgz -C pkg)
src="$work/pkg/package/dist/sprite_icons"
pkg_version="$(jq -r .version "$work/pkg/package/package.json")"
[[ "$(jq -r .license "$work/pkg/package/package.json")" == "MIT" ]] || {
  echo "unexpected license" >&2
  exit 1
}

# name:colour (GitLab's own status colours: open green, merged purple, closed
# red, draft neutral)
icons=(
  merge-request-open:#2da160
  merge:#7b58cf
  merge-request-close:#dd2b0e
  merge-request:#737278
  pipeline:#1f75cb
  status_success:#2da160
  status_failed:#dd2b0e
  status_running:#1f75cb
  status_pending:#c17d10
  status_canceled:#737278
  status_skipped:#737278
  status_manual:#1f75cb
  status_created:#737278
)

out="$root/src/gitlab-icons.mjs"
{
  cat <<HEADER
// GitLab iconography for the card headers: 48x48 PNG data URIs (generated by
// scripts/gen-gitlab-icons.sh, do not edit by hand).
//
// The glyphs come from @gitlab/svgs ${pkg_version} (MIT, Copyright (c) 2011-present
// GitLab Inc.), flattened to one GitLab status colour each so they stay legible
// on light and dark themes.

export const GITLAB_ICONS = {
HEADER
  for spec in "${icons[@]}"; do
    name="${spec%%:*}"
    colour="${spec##*:}"
    sed "s/<path /<path fill=\"${colour}\" /g" "$src/${name}.svg" >"$work/${name}.svg"
    magick -background none -density 768 "$work/${name}.svg" -resize 48x48 \
      -depth 8 -strip -define png:compression-level=9 "PNG32:$work/${name}.png"
    printf "  '%s':\n    'data:image/png;base64,%s',\n" "$name" "$(base64 -w0 "$work/${name}.png")"
  done
  echo '};'
} >"$out"
echo "wrote $out"

# Compact variants for list rows (one image per row, so a few hundred bytes
# each matter): 32x32 palette PNGs shown at 16px. `draft` is the neutral
# merge request glyph.
small_icons=(
  merge-request-open:#2da160
  merge:#7b58cf
  merge-request-close:#dd2b0e
  merge-request:#737278
  status_success:#2da160
  status_failed:#dd2b0e
  status_running:#1f75cb
  status_pending:#c17d10
  status_canceled:#737278
  status_skipped:#737278
  status_manual:#1f75cb
  status_created:#737278
)

small_out="$root/src/gitlab-icons-small.mjs"
{
  cat <<HEADER
// Compact GitLab icons for list rows: 32x32 palette PNG data URIs, shown at
// 16px (generated by scripts/gen-gitlab-icons.sh, do not edit by hand). Same
// glyphs and colours as gitlab-icons.mjs, a fraction of the bytes, because a
// list repeats one icon per row and a card is limited in size. The
// \`merge-request\` key is the neutral glyph of a draft.
//
// The glyphs come from @gitlab/svgs ${pkg_version} (MIT, Copyright (c) 2011-present
// GitLab Inc.).

export const GITLAB_ICONS_SMALL = {
HEADER
  for spec in "${small_icons[@]}"; do
    name="${spec%%:*}"
    colour="${spec##*:}"
    sed "s/<path /<path fill=\"${colour}\" /g" "$src/${name}.svg" >"$work/s-${name}.svg"
    magick -background none -density 768 "$work/s-${name}.svg" -resize 32x32 \
      -depth 8 -strip -define png:compression-level=9 "PNG8:$work/s-${name}.png"
    printf "  '%s':\n    'data:image/png;base64,%s',\n" "$name" "$(base64 -w0 "$work/s-${name}.png")"
  done
  echo '};'
} >"$small_out"
echo "wrote $small_out"
