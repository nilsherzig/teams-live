#!/usr/bin/env bash
# Regenerates src/mr-badges.mjs: GitLab-style merge request state badges (a light tinted
# rounded pill with the state glyph and the state in words, "Open", "Merged",
# "Closed", "Draft") as embedded PNG data URIs. Adaptive Cards cannot paint a
# pill in GitLab's own colours (the card host only offers its theme styles), so
# each state is a small static image with its own light background, which
# stays readable on a light and a dark Teams theme. Needs npm, tar and
# ImageMagick (with the librsvg delegate).
#
# Usage: scripts/gen-mr-badges.sh [VERSION]   (default: the version of
# gitlab-icons-small.mjs, 3.174.0; set FONT to a bold sans-serif .ttf)

set -euo pipefail

version="${1:-3.174.0}"
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
font="${FONT:-$(fc-match -f '%{file}' 'sans-serif:bold')}"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

(cd "$work" && npm pack --silent "@gitlab/svgs@${version}" >/dev/null 2>&1 && mkdir pkg && tar -xzf ./*.tgz -C pkg)
src="$work/pkg/package/dist/sprite_icons"
[[ "$(jq -r .license "$work/pkg/package/package.json")" == "MIT" ]] || {
  echo "unexpected license" >&2
  exit 1
}

# key:label:glyph:glyph colour:background:border:text colour
# GitLab's light state badges: a tinted pill (open teal, merged blue, closed
# red, draft neutral) with the glyph and the text in the dark shade of the same
# hue, which keeps WCAG AA contrast (4.5:1) on the tinted background.
badges=(
  "open:Open:merge-request-open:#0b5a4b:#c5ece3:#7fcab8:#0b5a4b"
  "merged:Merged:merge:#0a2f5c:#9fc5f2:#5b98e0:#0a2f5c"
  "closed:Closed:merge-request-close:#8a2415:#fbe5e1:#f0a79b:#8a2415"
  "draft:Draft:merge-request:#4a4950:#ececef:#bfbfc3:#4a4950"
)

# Drawn at 3x and shown at 1x (a 48-colour palette keeps each badge near 2 KB,
# a card is limited in size): 22px high, 14px glyph, 12px bold text.
s=3
h=$((22 * s))
glyph=$((14 * s))
font_px=$((12 * s))
pad=$((8 * s))
gap=$((4 * s))

out="$root/src/mr-badges.mjs"
{
  cat <<HEADER
// GitLab-style merge request state badges: a pill with the state glyph and the
// state in words, as 3x PNG data URIs shown at \`width\` x \`height\` pixels
// (generated by scripts/gen-mr-badges.sh, do not edit by hand).
//
// The glyphs come from @gitlab/svgs ${version} (MIT, Copyright (c) 2011-present
// GitLab Inc.); the text is rendered into the image, so \`alt\` carries the
// state for screen readers.

export const MR_BADGES = {
HEADER
  for spec in "${badges[@]}"; do
    IFS=: read -r key label icon glyph_colour bg border text_colour <<<"$spec"
    sed "s/<path /<path fill=\"${glyph_colour}\" /g" "$src/${icon}.svg" >"$work/${key}.svg"
    magick -background none -density 1536 "$work/${key}.svg" -resize "${glyph}x${glyph}" \
      "PNG32:$work/${key}-glyph.png"
    magick -background none -fill "$text_colour" -font "$font" -pointsize "$font_px" \
      "label:${label}" -trim +repage "PNG32:$work/${key}-text.png"
    text_w="$(magick identify -format '%w' "$work/${key}-text.png")"
    text_h="$(magick identify -format '%h' "$work/${key}-text.png")"
    w=$((pad + glyph + gap + text_w + pad))
    w=$(((w + s - 1) / s * s))
    r=$((h / 2))
    magick -size "${w}x${h}" xc:none -fill "$bg" -stroke "$border" -strokewidth "$s" \
      -draw "roundrectangle $((s / 2)),$((s / 2)) $((w - 1 - s / 2)),$((h - 1 - s / 2)) $r,$r" \
      "$work/${key}-glyph.png" -geometry "+${pad}+$(((h - glyph) / 2))" -composite \
      "$work/${key}-text.png" -geometry "+$((pad + glyph + gap))+$(((h - text_h) / 2))" -composite \
      +dither -colors 48 -strip -define png:format=png8 -define png:compression-level=9 \
      "$work/${key}.png"
    printf "  '%s': {\n    alt: '%s',\n    width: %d,\n    height: %d,\n    url:\n      'data:image/png;base64,%s',\n  },\n" \
      "$key" "$label" "$((w / s))" "$((h / s))" "$(base64 -w0 "$work/${key}.png")"
  done
  echo "};"
} >"$out"
echo "wrote $out"
