#!/usr/bin/env bash
# Regenerates src/card-icons.mjs: the service logos of the card headers as
# embedded PNG data URIs, drawn at 3x (48px) for a 16px slot. The glyphs come
# from Simple Icons (CC0 1.0), flattened to one colour each. A 16-colour palette
# keeps a logo near 500 characters instead of 3-5 KB: a card is limited in size
# (MAX_CARD_BYTES), every header carries one, and the room it frees is what the
# profile pictures and badges of the card need. Needs npm, tar and ImageMagick
# (with the librsvg delegate).
#
# Usage: scripts/gen-card-icons.sh [VERSION]   (default: simple-icons 14.15.0)

set -euo pipefail

version="${1:-14.15.0}"
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

(cd "$work" && npm pack --silent "simple-icons@${version}" >/dev/null 2>&1 && mkdir pkg && tar -xzf ./*.tgz -C pkg)
src="$work/pkg/package/icons"

# key:Simple Icons slug:colour (GitLab orange, Atlassian blue: legible on a
# light and a dark theme)
icons=(
  "gitlab:gitlab:#FC6D26"
  "jira:jira:#2684FF"
  "confluence:confluence:#2684FF"
  "opsgenie:opsgenie:#2684FF"
)

px=16
s=3
out="$root/src/card-icons.mjs"
{
  cat <<HEADER
// Service logos for the card headers: ${px}px slots, 3x PNG data URIs so a card is
// self-contained (no image fetch by Teams, no dependency on an external host).
// Generated by scripts/gen-card-icons.sh, do not edit by hand.
//
// The glyphs come from Simple Icons ${version} (CC0 1.0), flattened to one
// colour each (GitLab orange, Atlassian blue) so they stay legible on light and
// dark themes. The logos are trademarks of their owners and only identify the
// service a card came from.

HEADER
  for spec in "${icons[@]}"; do
    IFS=: read -r key slug colour <<<"$spec"
    sed "s/<path /<path fill=\"${colour}\" /" "$src/${slug}.svg" >"$work/${key}.svg"
    magick -background none -density 1536 "$work/${key}.svg" -resize "$((px * s))x$((px * s))" \
      +dither -colors 16 -strip -define png:format=png8 -define png:compression-level=9 "$work/${key}.png"
    printf "const %s_PNG =\n  'data:image/png;base64,%s';\n\n" "${key^^}" "$(base64 -w0 "$work/${key}.png")"
  done
  cat <<'FOOTER'
export const SERVICE_ICONS = {
  gitlab: GITLAB_PNG,
  jira: JIRA_PNG,
  confluence: CONFLUENCE_PNG,
  opsgenie: OPSGENIE_PNG,
};
FOOTER
} >"$out"
echo "wrote $out"
