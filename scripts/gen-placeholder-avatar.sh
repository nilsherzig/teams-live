#!/usr/bin/env bash
# Regenerates src/placeholder-avatar.mjs: the neutral silhouette shown in place
# of a profile picture for a person who has none (or who cannot be matched to
# a profile with certainty). A 36x36 PNG data URI on a square gray ground (the
# card crops it to a circle at 18px), drawn at 4x and reduced to a tiny
# palette so it costs a few hundred characters on a card. Needs ImageMagick.
#
# Usage: scripts/gen-placeholder-avatar.sh

set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

# Mid gray ground and a light silhouette (head and shoulders): legible on
# light and dark themes.
magick -size 144x144 xc:'#9aa3ad' -fill '#eef1f4' \
  -draw 'circle 72,56 72,30' \
  -draw 'ellipse 72,150 54,50 180,360' \
  -resize 36x36 +dither -colors 8 -depth 8 -strip \
  -define png:compression-level=9 -define png:format=png8 "PNG8:$work/avatar.png"

cat >"$root/src/placeholder-avatar.mjs" <<HEADER
// Neutral silhouette for a person without a profile picture: a 36x36 palette
// PNG data URI (generated by scripts/gen-placeholder-avatar.sh, do not edit by
// hand). It is a static image, never fetched, and shown like a photo (18px,
// cropped round).

export const PLACEHOLDER_AVATAR =
  'data:image/png;base64,$(base64 -w0 "$work/avatar.png")';
HEADER
echo "wrote $root/src/placeholder-avatar.mjs"
