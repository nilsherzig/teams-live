#!/usr/bin/env bash
# Regenerates src/tv-logos.mjs: the channel logos of the TV cards (ARD, ZDF,
# Tagesschau) as small embedded PNG data URIs, so a card is self-contained (no
# image fetch by Teams, no dependency on an external host at run time).
#
# - ARD and Tagesschau: the public domain logos on Wikimedia Commons ("ARD 2019
#   logo.svg", "Tagesschau Logo 2015.svg"; Commons marks both as public domain
#   because of their simple geometry, and as trademarked).
# - ZDF: the Simple Icons glyph (CC0 1.0), flattened to ZDF orange.
#
# The logos are trademarks of their owners and only identify the channel. Each
# one sits on a small white chip, so it stays legible on a light and a dark
# Teams theme (the ARD and Tagesschau wordmarks are dark blue and black).
#
# Needs curl, npm, tar, jq and ImageMagick (with the librsvg delegate).
#
# Usage: scripts/gen-tv-logos.sh

set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
ua="teams-live-logo-generator/1.0"
commons="https://upload.wikimedia.org/wikipedia/commons"

curl -fsS -A "$ua" -o "$work/ard.svg" "$commons/7/7c/ARD_2019_logo.svg"
curl -fsS -A "$ua" -o "$work/tagesschau.svg" "$commons/3/3c/Tagesschau_Logo_2015.svg"
(cd "$work" && npm pack --silent simple-icons >/dev/null 2>&1 && tar -xzf ./simple-icons-*.tgz)
[[ "$(jq -r .license "$work/package/package.json")" == "CC0-1.0" ]] || {
  echo "unexpected license for simple-icons" >&2
  exit 1
}
si_version="$(jq -r .version "$work/package/package.json")"
sed 's/<path /<path fill="#fa7d19" /g' "$work/package/icons/zdf.svg" >"$work/zdf.svg"

# key:alt text:inner height (px at 1x):inner max width (px at 1x)
logos=(
  "ard:ARD:16:64"
  "zdf:ZDF:16:16"
  "tagesschau:Tagesschau:16:84"
)

s=3   # drawn at 3x, shown at 1x
pad=2 # white chip padding, px at 1x
out="$root/src/tv-logos.mjs"
{
  cat <<HEADER
// Channel logos of the TV cards (src/tv-cards.mjs), each on a small white chip, as
// 3x PNG data URIs (generated by scripts/gen-tv-logos.sh, do not edit by hand).
// \`width\` and \`height\` are the size to show it at, in px; \`alt\` is the logo in
// words for screen readers.
//
// ARD and Tagesschau: public domain on Wikimedia Commons. ZDF: Simple Icons
// ${si_version} (CC0 1.0). The logos are trademarks of their owners and only
// identify the channel.

export const TV_LOGOS = {
HEADER
  for spec in "${logos[@]}"; do
    IFS=: read -r key alt h w <<<"$spec"
    magick -background none -density 1536 "$work/${key}.svg" -resize "$((w * s))x$((h * s))" \
      -background white -gravity center -bordercolor white -border "$((pad * s))" -alpha remove -alpha off \
      +dither -colors 16 -strip -define png:format=png8 -define png:compression-level=9 "$work/${key}.png"
    read -r pw ph <<<"$(magick identify -format '%w %h' "$work/${key}.png")"
    printf "  %s: {\n    alt: '%s',\n    width: %d,\n    height: %d,\n    url:\n      'data:image/png;base64,%s',\n  },\n" \
      "$key" "$alt" "$((pw / s))" "$((ph / s))" "$(base64 -w0 "$work/${key}.png")"
  done
  echo "};"
} >"$out"
echo "wrote $out"
