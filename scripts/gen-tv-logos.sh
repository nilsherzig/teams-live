#!/usr/bin/env bash
# Regenerates src/tv-logos.mjs: the channel logos of the TV cards (ARD, ZDF,
# Tagesschau) as small embedded PNG data URIs, so a card is self-contained (no
# image fetch by Teams, no dependency on an external host at run time).
#
# They are compact marks drawn for being shown small, with a transparent
# background (no white chip), so they read on a light and a dark Teams theme:
#
# - ARD (Das Erste): the "Eins" ring, the favicon of ard.de (a round badge).
# - ZDF: the Simple Icons glyph (CC0 1.0), the orange ZDF mark with the letters
#   knocked out, trimmed to its bounds.
# - Tagesschau: the app icon of tagesschau.de (the globe, 144 px version), with
#   rounded corners.
#
# The logos are trademarks of their owners and only identify the channel.
#
# Needs curl, npm, tar, jq, pngquant and ImageMagick (with the librsvg delegate).
#
# Usage: scripts/gen-tv-logos.sh

set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
ua="Mozilla/5.0 (teams-live logo generator)"

curl -fsSL -A "$ua" -o "$work/ard.svg" "https://www.ard.de/resources/assets/image/favicon/favicon.svg"
(cd "$work" && npm pack --silent simple-icons >/dev/null 2>&1 && tar -xzf ./simple-icons-*.tgz)
[[ "$(jq -r .license "$work/package/package.json")" == "CC0-1.0" ]] || {
  echo "unexpected license for simple-icons" >&2
  exit 1
}
si_version="$(jq -r .version "$work/package/package.json")"
sed 's/<path /<path fill="#fa7d19" /g' "$work/package/icons/zdf.svg" >"$work/zdf.svg"
curl -fsSL -A "$ua" -o "$work/tagesschau.png" \
  "https://www.tagesschau.de/resources/assets/image/favicon/apple-icon-144x144.png"

# key:alt text:height (px at 1x; the width follows the mark)
logos=(
  "ard:ARD:20"
  "zdf:ZDF:20"
  "tagesschau:Tagesschau:20"
)

s=3 # drawn at 3x, shown at 1x
out="$root/src/tv-logos.mjs"
{
  cat <<HEADER
// Channel logos of the TV cards (src/tv-cards.mjs): compact marks of ARD, ZDF and
// Tagesschau as 3x PNG data URIs with a transparent background (generated by
// scripts/gen-tv-logos.sh, do not edit by hand). \`width\` and \`height\` are the
// size to show it at, in px; \`alt\` is the logo in words for screen readers.
//
// ARD and Tagesschau: the site icons of ard.de and tagesschau.de. ZDF: Simple Icons
// ${si_version} (CC0 1.0). The logos are trademarks of their owners and only
// identify the channel.

export const TV_LOGOS = {
HEADER
  for spec in "${logos[@]}"; do
    IFS=: read -r key alt size <<<"$spec"
    h="$((size * s))"
    round=() # the app icon is a square: round its corners like a tile; the ARD ring is round already
    if [[ -f "$work/${key}.svg" ]]; then
      src="$work/${key}.svg"
    else
      src="$work/${key}.png"
      round=(\( -size "${h}x${h}" xc:none -fill white -draw "roundrectangle 0,0,$((h - 1)),$((h - 1)),12,12" \) -compose DstIn -composite)
    fi
    # Trim to the mark (so no empty margin eats the small size), fit the height, keep alpha.
    magick -background none -density 1536 "$src" -trim +repage -resize "x${h}" -alpha set \
      "${round[@]}" -strip -define png:format=png32 -define png:compression-level=9 "$work/${key}-full.png"
    # Palette with a real alpha channel (smooth edges, a few KB instead of several).
    pngquant --force --nofs --output "$work/${key}-out.png" 64 "$work/${key}-full.png"
    read -r pw ph <<<"$(magick identify -format '%w %h' "$work/${key}-out.png")"
    printf "  %s: {\n    alt: '%s',\n    width: %d,\n    height: %d,\n    url:\n      'data:image/png;base64,%s',\n  },\n" \
      "$key" "$alt" "$((pw / s))" "$((ph / s))" "$(base64 -w0 "$work/${key}-out.png")"
  done
  echo "};"
} >"$out"
echo "wrote $out"
