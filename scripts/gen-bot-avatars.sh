#!/usr/bin/env bash
# Regenerates src/bot-avatars.mjs: built-in profile pictures for well-known bot accounts that exist in no
# directory (Renovate). A 36x36 palette PNG data URI on a white ground (the card crops it to a circle at
# 18px), drawn at 4x from the Simple Icons logo (CC0 1.0) in the logo's blue. The logo is a trademark of its
# owner and only identifies the bot. Needs npm, tar and ImageMagick (with the librsvg delegate).
#
# Usage: scripts/gen-bot-avatars.sh [VERSION]   (default: simple-icons 14.15.0)

set -euo pipefail

version="${1:-14.15.0}"
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

(cd "$work" && npm pack --silent "simple-icons@${version}" >/dev/null 2>&1 && mkdir pkg && tar -xzf ./*.tgz -C pkg)

sed 's/<path /<path fill="#1A9BD7" /' "$work/pkg/package/icons/renovate.svg" >"$work/renovate.svg"
magick -background none -density 1536 "$work/renovate.svg" -resize 100x100 "$work/logo.png"
magick -size 144x144 xc:'#ffffff' "$work/logo.png" -gravity center -composite -resize 36x36 \
  +dither -colors 16 -depth 8 -strip -define png:compression-level=9 -define png:format=png8 "PNG8:$work/renovate.png"

cat >"$root/src/bot-avatars.mjs" <<HEADER
// Built-in profile pictures for well-known bot accounts that exist in no directory: 36x36 palette PNG data
// URIs (generated by scripts/gen-bot-avatars.sh, do not edit by hand), shown like a photo (18px, round).
// The glyph comes from Simple Icons ${version} (CC0 1.0); the logo is a trademark of its owner and only
// identifies the bot. A picture configured in \`avatars.overrides\` for the same name wins.

const RENOVATE =
  'data:image/png;base64,$(base64 -w0 "$work/renovate.png")';

/** [{ name, dataUri }] in the shape of \`loadAvatarOverrides\`: the display names Renovate's account goes by. */
export const BUILTIN_AVATAR_OVERRIDES = [
  'Renovate Service User',
  'Renovate Bot',
  'Renovate',
  'renovate-bot',
  'renovate[bot]',
].map((name) => ({ name, dataUri: RENOVATE }));
HEADER
echo "wrote $root/src/bot-avatars.mjs"
